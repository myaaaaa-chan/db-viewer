import {
  type ColumnInfo,
  columnName,
  type ForeignKeyInfo,
  type IndexInfo,
  schemaName,
  type TableKind,
  type TableRef,
  tableName,
} from "@myaaaaa_chan/db-viewer-core";
import { quoteIdentifier } from "../../sql/dialect";

// カタログの 1 行。結果はすべて文字列で受け取る（型の変換をドライバに任せない。03 §4）ので、数や真偽は
// この中の関数で読む。
export type CatalogRow = ReadonlyArray<string | null>;

// 関数もテーブルも pg_catalog を明示する。利用者が search_path の先頭に同名の関数を置いていても、
// メタデータの問い合わせは取り違えない。
// relkind: r 表 / p パーティション表 / f 外部表 / v ビュー / m マテリアライズドビュー
export const CATALOG_SQL = {
  // システムのスキーマ（pg_catalog、information_schema、pg_toast、接続ごとの一時スキーマ）は除く
  listSchemas: `SELECT nspname
FROM pg_catalog.pg_namespace
WHERE nspname NOT IN ('pg_catalog', 'information_schema')
  AND nspname NOT LIKE 'pg\\_toast%'
  AND nspname NOT LIKE 'pg\\_temp\\_%'
ORDER BY nspname`,

  listTables: `SELECT c.relname, c.relkind::text
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = $1 AND c.relkind IN ('r', 'p', 'f', 'v', 'm')
ORDER BY c.relname`,

  // $1 = スキーマ名、$2 = テーブル名
  relation: `SELECT c.oid::text, c.relkind::text
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = $1 AND c.relname = $2 AND c.relkind IN ('r', 'p', 'f', 'v', 'm')`,

  // 以下は $1 = pg_class の oid
  // 主キーでの順番は pg_index.indkey の並び（1 始まり）
  columns: `SELECT a.attname,
  pg_catalog.format_type(a.atttypid, a.atttypmod),
  a.attnotnull,
  pg_catalog.pg_get_expr(d.adbin, d.adrelid),
  a.attidentity::text,
  a.attgenerated::text,
  pk.ord::text
FROM pg_catalog.pg_attribute a
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
LEFT JOIN LATERAL (
  SELECT k.ord
  FROM pg_catalog.pg_index i
  CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(attnum, ord)
  WHERE i.indrelid = a.attrelid AND i.indisprimary AND k.attnum = a.attnum
) pk ON true
WHERE a.attrelid = $1::oid AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`,

  // キーの列だけ（INCLUDE の列は含めない）。式インデックスの列は式の文字列にする
  indexes: `SELECT ic.relname, i.indisunique, i.indisprimary, k.ord::text,
  CASE WHEN k.attnum = 0
    THEN pg_catalog.pg_get_indexdef(i.indexrelid, k.ord::int, true)
    ELSE a.attname
  END
FROM pg_catalog.pg_index i
JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(attnum, ord)
LEFT JOIN pg_catalog.pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum
WHERE i.indrelid = $1::oid AND k.ord <= i.indnkeyatts
ORDER BY i.indisprimary DESC, ic.relname, k.ord`,

  foreignKeys: `SELECT con.conname, k.ord::text, a.attname, fn.nspname, fc.relname, fa.attname
FROM pg_catalog.pg_constraint con
CROSS JOIN LATERAL unnest(con.conkey, con.confkey) WITH ORDINALITY AS k(attnum, fattnum, ord)
JOIN pg_catalog.pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
JOIN pg_catalog.pg_class fc ON fc.oid = con.confrelid
JOIN pg_catalog.pg_namespace fn ON fn.oid = fc.relnamespace
JOIN pg_catalog.pg_attribute fa ON fa.attrelid = con.confrelid AND fa.attnum = k.fattnum
WHERE con.conrelid = $1::oid AND con.contype = 'f'
ORDER BY con.conname, k.ord`,

  // DDL の材料。制約は主キー、ユニーク、チェック、排他、外部キーの順
  constraintDefinitions: `SELECT con.conname, pg_catalog.pg_get_constraintdef(con.oid, true)
FROM pg_catalog.pg_constraint con
WHERE con.conrelid = $1::oid AND con.contype IN ('p', 'u', 'c', 'x', 'f')
ORDER BY CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END,
  con.conname`,

  // 主キーやユニーク制約の裏にあるインデックスは、制約の定義に含まれるので除く
  standaloneIndexDefinitions: `SELECT pg_catalog.pg_get_indexdef(i.indexrelid, 0, true)
FROM pg_catalog.pg_index i
JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
WHERE i.indrelid = $1::oid
  AND NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint con
    WHERE con.conindid = i.indexrelid AND con.conrelid = i.indrelid AND con.contype IN ('p', 'u', 'x')
  )
ORDER BY ic.relname`,

  viewDefinition: `SELECT pg_catalog.pg_get_viewdef($1::oid, true)`,

  // $1 = 型の oid の配列、$2 = typmod の配列（同じ長さ）。結果は入力と同じ順
  typeNames: `SELECT pg_catalog.format_type(t.type_oid, t.type_mod)
FROM unnest($1::oid[], $2::int4[]) WITH ORDINALITY AS t(type_oid, type_mod, ord)
ORDER BY t.ord`,
} as const;

export const kindOfRelation = (relkind: string): TableKind =>
  relkind === "v" || relkind === "m" ? "view" : "table";

export type ColumnRow = {
  readonly name: string;
  readonly dbType: string;
  readonly notNull: boolean;
  // pg_get_expr の結果。通常の列では既定値、生成列では生成する式
  readonly defaultExpr: string | null;
  // 'a' = GENERATED ALWAYS、'd' = GENERATED BY DEFAULT、'' = IDENTITY ではない
  readonly identity: string;
  readonly generated: boolean;
  readonly primaryKeyPosition: number | null;
};

const text = (value: string | null | undefined): string => value ?? "";

export const columnRowFromRow = (row: CatalogRow): ColumnRow => ({
  name: text(row[0]),
  dbType: text(row[1]),
  notNull: row[2] === "t",
  defaultExpr: row[3] ?? null,
  identity: text(row[4]),
  generated: row[5] === "s",
  primaryKeyPosition: row[6] === null || row[6] === undefined ? null : Number(row[6]),
});

export const toColumnInfo = (row: ColumnRow): ColumnInfo => ({
  name: columnName(row.name),
  dbType: row.dbType,
  nullable: !row.notNull,
  // 生成列の式と IDENTITY は、挿入時に使う既定値ではない
  defaultValue: row.generated || row.identity !== "" ? null : row.defaultExpr,
  primaryKeyPosition: row.primaryKeyPosition,
});

// 並びが同じキーの行は連続している（SQL の ORDER BY）ので、出てきた順に束ねる。
const groupByKey = <T>(
  rows: ReadonlyArray<CatalogRow>,
  keyOf: (row: CatalogRow) => string,
  build: (key: string, group: ReadonlyArray<CatalogRow>) => T,
): ReadonlyArray<T> => {
  const groups = new Map<string, Array<CatalogRow>>();
  for (const row of rows) {
    const key = keyOf(row);
    const group = groups.get(key);
    if (group) group.push(row);
    else groups.set(key, [row]);
  }
  return Array.from(groups, ([key, group]) => build(key, group));
};

export const indexesFromRows = (rows: ReadonlyArray<CatalogRow>): ReadonlyArray<IndexInfo> =>
  groupByKey(
    rows,
    (row) => text(row[0]),
    (name, group) => ({
      name,
      columns: group.map((row) => text(row[4])),
      unique: group[0]?.[1] === "t",
      primary: group[0]?.[2] === "t",
    }),
  );

export const foreignKeysFromRows = (
  rows: ReadonlyArray<CatalogRow>,
): ReadonlyArray<ForeignKeyInfo> =>
  groupByKey(
    rows,
    (row) => text(row[0]),
    (name, group) => ({
      name,
      columns: group.map((row) => columnName(text(row[2]))),
      references: {
        table: { schema: schemaName(text(group[0]?.[3])), name: tableName(text(group[0]?.[4])) },
        columns: group.map((row) => columnName(text(row[5]))),
      },
    }),
  );

export type DdlInput = {
  readonly ref: TableRef;
  readonly relkind: string;
  readonly columns: ReadonlyArray<ColumnRow>;
  // pg_get_constraintdef の結果（"PRIMARY KEY (id)" など）
  readonly constraints: ReadonlyArray<{ readonly name: string; readonly definition: string }>;
  // pg_get_indexdef の結果（; なし）
  readonly indexDefinitions: ReadonlyArray<string>;
  // ビューとマテリアライズドビューのときだけ
  readonly viewDefinition: string | null;
};

const columnDefinition = (row: ColumnRow): string => {
  const parts = [quoteIdentifier("postgres", row.name), row.dbType];
  if (row.generated && row.defaultExpr !== null) {
    parts.push(`GENERATED ALWAYS AS (${row.defaultExpr}) STORED`);
  } else if (row.identity !== "") {
    parts.push(`GENERATED ${row.identity === "a" ? "ALWAYS" : "BY DEFAULT"} AS IDENTITY`);
  } else if (row.defaultExpr !== null) {
    parts.push(`DEFAULT ${row.defaultExpr}`);
  }
  if (row.notNull) parts.push("NOT NULL");
  return parts.join(" ");
};

const HEADERS: Readonly<Record<string, string>> = {
  r: "CREATE TABLE",
  p: "CREATE TABLE",
  f: "CREATE FOREIGN TABLE",
  v: "CREATE VIEW",
  m: "CREATE MATERIALIZED VIEW",
};

/**
 * カタログの情報から作る CREATE 文。近似であって、実際の定義とは一致しない（パーティションの指定、
 * 照合順序、ストレージの設定、外部表のサーバーなどは含めない。03 §4）。
 * 識別子はこちらでクォートする。式や制約の文はカタログが返したものをそのまま使う。
 */
export const buildDdl = (input: DdlInput): string => {
  const name = `${quoteIdentifier("postgres", input.ref.schema)}.${quoteIdentifier("postgres", input.ref.name)}`;
  const header = HEADERS[input.relkind] ?? "CREATE TABLE";
  const indexes = input.indexDefinitions.map((definition) => `${definition};`);

  const create =
    input.viewDefinition !== null
      ? `${header} ${name} AS\n${input.viewDefinition.trim()}`
      : buildTable(header, name, input);
  return [create, ...indexes].join("\n\n");
};

const buildTable = (header: string, name: string, input: DdlInput): string => {
  const lines = [
    ...input.columns.map(columnDefinition),
    ...input.constraints.map(
      ({ name: constraint, definition }) =>
        `CONSTRAINT ${quoteIdentifier("postgres", constraint)} ${definition}`,
    ),
  ];
  return lines.length === 0
    ? `${header} ${name} ();`
    : `${header} ${name} (\n${lines.map((line) => `  ${line}`).join(",\n")}\n);`;
};
